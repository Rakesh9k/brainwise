import crypto from 'node:crypto';
import { scheduledReportRepository } from '../repositories/scheduledReportRepository';
import { businessProfileRepository } from '../repositories/businessProfileRepository';
import { goalRepository } from '../repositories/goalRepository';
import { proactiveInsightRepository } from '../repositories/proactiveInsightRepository';
import { businessMetricRepository } from '../repositories/businessMetricRepository';
import type { ScheduledIntelligenceReportEntity } from '../types/api';

export class ScheduledIntelligenceService {
  /**
   * Generates a scheduled intelligence report (daily summary, weekly review, or monthly growth digest)
   */
  public async generateReport(params: {
    workspaceId: string;
    frequency: 'DAILY' | 'WEEKLY' | 'MONTHLY';
    reportType?: ScheduledIntelligenceReportEntity['reportType'];
    channel?: 'IN_APP' | 'EMAIL';
  }): Promise<ScheduledIntelligenceReportEntity> {
    const {
      workspaceId,
      frequency,
      reportType = frequency === 'DAILY'
        ? 'BUSINESS_SUMMARY'
        : frequency === 'WEEKLY'
          ? 'WEEKLY_REVIEW'
          : 'MONTHLY_GROWTH',
      channel = 'IN_APP',
    } = params;

    const profile = await businessProfileRepository.getProfile(workspaceId);
    const goals = await goalRepository.listByWorkspace(workspaceId);
    const activeInsights = await proactiveInsightRepository.listByWorkspace(workspaceId, {
      status: 'ACTIVE',
    });
    const recentMetrics = await businessMetricRepository.listByWorkspace(workspaceId);

    const businessName = profile?.businessName || 'Business';
    const nowIso = new Date().toISOString();

    // 1. Synthesize Goal Progress
    const goalProgressSummary: Record<
      string,
      { current: number; target: number; onTrack: boolean }
    > = {};
    for (const g of goals) {
      const onTrack = g.targetValue > 0 ? g.currentValue / g.targetValue >= 0.5 : true;
      const key = g.title || 'Goal';
      goalProgressSummary[key] = {
        current: g.currentValue,
        target: g.targetValue,
        onTrack,
      };
    }

    // 2. Identify Active Anomalies and Opportunities
    const activeAnomalies = activeInsights
      .filter((i) => i.triggerType === 'PERFORMANCE_DROP' || i.triggerType === 'BUDGET_CEILING')
      .map((i) => i.title);

    const topOpportunities = activeInsights
      .filter(
        (i) => i.triggerType === 'MARKET_OPPORTUNITY' || i.triggerType === 'UNDERPROMOTED_PRODUCT'
      )
      .map((i) => i.title);

    // 3. Key Findings
    const keyFindings: string[] = [
      `${goals.length} active business goals tracked across departments.`,
      `${activeInsights.length} active proactive insights generated by intelligence engine.`,
    ];

    if (recentMetrics.length > 0) {
      keyFindings.push(
        `${recentMetrics.length} real-time business telemetry metrics ingested in current period.`
      );
    }

    // 4. Executive Summary Narrative
    const onTrackGoalsCount = goals.filter((g) => goalProgressSummary[g.title || 'Goal']?.onTrack).length;
    const summary = `${frequency} Intelligence Brief for ${businessName}: ${onTrackGoalsCount}/${goals.length || 1} strategic targets on track. ${activeAnomalies.length} risk signals require attention.`;

    const reportId = `rep_sched_${Date.now()}_${crypto.randomBytes(4).toString('hex')}`;

    const reportEntity: ScheduledIntelligenceReportEntity = {
      reportId,
      workspaceId,
      frequency,
      reportType,
      summary,
      keyFindings,
      activeAnomalies,
      topOpportunities,
      goalProgressSummary,
      channel,
      notificationDispatched: true,
      generatedAt: nowIso,
    };

    return await scheduledReportRepository.create(reportEntity);
  }
}

export const scheduledIntelligenceService = new ScheduledIntelligenceService();
